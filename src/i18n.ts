// English + Spanish UI strings. VS Code locale decides by default
// (vscode.env.language), with an optional manual override setting.
export type Lang = 'es' | 'en';
export type LangOverride = 'auto' | Lang;

export function resolveLang(envLanguage: string | undefined, override: LangOverride): Lang {
  if (override === 'es' || override === 'en') return override;
  const tag = (envLanguage || '').toLowerCase();
  if (tag === 'es' || tag.startsWith('es-') || tag.startsWith('es_')) return 'es';
  return 'en';
}

